	const DICTS = { 'zh-CN': zh, en: en }
	const LOCALES = ['zh-CN', 'en']
	// node 单测里各模块默认中文（与既有断言一致）；浏览器里由 app.js 在启动时按宿主 / navigator 设定
	let locale = 'zh-CN'
	const listeners = []

	/** 宿主契约：zh 开头 → zh-CN，其它一律 en；空值返回 null（交给回退） */
	function normalize(tag) {
		if (tag == null || tag === '') return null
		const s = String(tag).trim().toLowerCase()
		if (!s) return null
		return s.indexOf('zh') === 0 ? 'zh-CN' : 'en'
	}

	/** navigator.language 回退；拿不到时给 en（与宿主「跟随系统」的非中文分支一致） */
	function fallbackLocale(nav) {
		const n = nav || (typeof navigator !== 'undefined' ? navigator : null)
		const lang = n && (n.language || (Array.isArray(n.languages) && n.languages[0]))
		return normalize(lang) || 'en'
	}

	function format(str, vars) {
		if (!vars) return str
		return str.replace(/\{(\w+)\}/g, function (m, k) {
			return Object.prototype.hasOwnProperty.call(vars, k) && vars[k] != null ? String(vars[k]) : m
		})
	}

	function t(key, vars) {
		const d = DICTS[locale] || en
		let s = d[key]
		if (s == null) s = en[key]
		if (s == null) return key
		return format(s, vars)
	}

	/**
	 * 惰性消息：保存键与参数，toString() 时才按**当前**语言取词。
	 * 参数里嵌套的惰性消息同样按当前语言展开（format 里 String(v) 会再调它的 toString）。
	 * 状态条 / 诊断这类「语言切换要重绘」的地方存它，而不是存已翻译的文本。
	 */
	function Msg(key, vars) {
		this.key = key
		this.vars = vars || null
	}
	Msg.prototype.toString = function () {
		if (this.parts) return this.parts.map(String).join('')
		return t(this.key, this.vars)
	}
	Msg.prototype.valueOf = Msg.prototype.toString
	Msg.prototype.toJSON = Msg.prototype.toString

	function msg(key, vars) {
		return new Msg(key, vars)
	}

	/** 惰性拼接：几段文案（惰性消息或普通串）按当前语言拼成一段，用作消息参数 */
	function join(parts) {
		const m = new Msg(null, null)
		m.parts = (parts || []).filter(function (p) { return p != null && p !== '' })
		return m
	}

	function isMsg(v) {
		return v instanceof Msg
	}

	function has(key) {
		return Object.prototype.hasOwnProperty.call(en, key)
	}

	function getLocale() {
		return locale
	}

	/** 设定语言；返回是否真的变了。变化时同步通知订阅者（界面就地重绘） */
	function setLocale(tag) {
		const next = normalize(tag) || 'en'
		if (next === locale) return false
		locale = next
		for (let i = 0; i < listeners.length; i++) {
			try { listeners[i](locale) } catch (e) { /* 一个订阅者出错不影响其它 */ }
		}
		return true
	}

	function onChange(fn) {
		if (typeof fn !== 'function') return function () {}
		listeners.push(fn)
		return function () {
			const i = listeners.indexOf(fn)
			if (i >= 0) listeners.splice(i, 1)
		}
	}

	const ATTRS = [
		['data-i18n-title', 'title'],
		['data-i18n-placeholder', 'placeholder'],
		['data-i18n-aria', 'aria-label'],
	]

	/** 把静态文案按当前语言刷进 DOM（textContent 与 title / placeholder / aria-label） */
	function apply(doc) {
		const d = doc || (typeof document !== 'undefined' ? document : null)
		if (!d || typeof d.querySelectorAll !== 'function') return 0
		let n = 0
		const nodes = d.querySelectorAll('[data-i18n],[data-i18n-title],[data-i18n-placeholder],[data-i18n-aria]')
		for (let i = 0; i < nodes.length; i++) {
			const el = nodes[i]
			const k = el.getAttribute('data-i18n')
			if (k) { el.textContent = t(k); n++ }
			for (let j = 0; j < ATTRS.length; j++) {
				const ak = el.getAttribute(ATTRS[j][0])
				if (ak) { el.setAttribute(ATTRS[j][1], t(ak)); n++ }
			}
		}
		if (d.documentElement && typeof d.documentElement.setAttribute === 'function') d.documentElement.setAttribute('lang', locale === 'zh-CN' ? 'zh-CN' : 'en')
		if ('title' in d) d.title = t('app.title')
		return n
	}

	const api = {
		LOCALES: LOCALES,
		DICTS: DICTS,
		t: t,
		msg: msg,
		join: join,
		isMsg: isMsg,
		has: has,
		normalize: normalize,
		fallbackLocale: fallbackLocale,
		getLocale: getLocale,
		setLocale: setLocale,
		onChange: onChange,
		apply: apply,
	}
	global.PowerI18n = api
	if (typeof module !== 'undefined' && module.exports) module.exports = api
